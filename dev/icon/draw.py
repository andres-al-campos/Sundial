"""Draw AppIcon.svg: an S whose top half is a sundial's gnomon and whose bottom half is its dial.

Both halves are the same curve, the bottom one turned 180°, so the S is balanced. The curve is
a piece of an oval; each end runs on halfway between that oval and a straight line, which
keeps the top on the gnomon's edge without making the S angular. Run render.sh afterwards.
"""
import math, pathlib

RX, ASPECT = 63, 0.7     # the oval both halves are cut from
GNOMON_DEG = 42          # the gnomon's edge against its base
A = 60                   # where the bottom half starts on its oval
GAP = 36                 # the break between the halves, at the same x
BLEND = 0.5              # ends: 0 straight, 1 the oval's own curve
STROKE = 11              # one weight for every line; thinner vanished at 16px
GROUND, INK = "#F28C28", "#FFFFFF"

ry = RX * ASPECT
pt = lambda c, th: (c[0] + RX * math.cos(math.radians(th)), c[1] - ry * math.sin(math.radians(th)))
# The top half starts where the oval's tangent makes GNOMON_DEG with the horizontal.
s = 180 - math.degrees(math.atan(ASPECT / math.tan(math.radians(GNOMON_DEG))))

C1 = (0.0, 0.0); P1 = pt(C1, A)
M = (P1[0], P1[1] + GAP / 2); C2 = (2 * M[0], 2 * M[1])
turn = lambda p: (2 * M[0] - p[0], 2 * M[1] - p[1])
S0, F, right = pt(C2, s), pt(C2, A + 180), C1[0] + RX
r = math.radians(s); t = (-RX * math.sin(r), -ry * math.cos(r)); n = math.hypot(*t); u = (-t[0] / n, -t[1] / n)

N = 120
core = [pt(C2, s + (A + 180 - s) * i / N) for i in range(N + 1)]
e = s
while pt(C2, e)[0] < right: e -= 0.05
Ls = (right - S0[0]) / u[0]
ext = []
for i in range(N + 1):
    f = i / N
    st = (S0[0] + u[0] * Ls * f, S0[1] + u[1] * Ls * f); ov = pt(C2, s + (e - s) * f)
    ext.append(((1 - BLEND) * st[0] + BLEND * ov[0], (1 - BLEND) * st[1] + BLEND * ov[1]))
top = ext[::-1] + core[1:]
bottom = [turn(p) for p in top]
B = (S0[0] + t[0] * (F[1] - S0[1]) / t[1], F[1])

pts = top + bottom + [B]
xs, ys = [p[0] for p in pts], [p[1] for p in pts]
sc = min(122 / (max(xs) - min(xs)), 122 / (max(ys) - min(ys)))
ox, oy = 85 - sc * (max(xs) + min(xs)) / 2, 85 - sc * (max(ys) + min(ys)) / 2
fmt = lambda p: f"{ox + sc * p[0]:.2f} {oy + sc * p[1]:.2f}"
line = lambda ps: "M" + " L".join(fmt(p) for p in ps)

svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <!-- Generated by draw.py. macOS icon grid: an 824pt body centered on 1024; drawn on a 170 grid. -->
  <g transform="translate(100 100) scale(4.847)" fill="none" stroke-linecap="round" stroke-linejoin="round">
    <rect width="170" height="170" rx="38" fill="{GROUND}"/>
    <g stroke="{INK}" stroke-width="{STROKE}">
      <path d="{line([S0, B, F])}"/>
      <path d="{line(top)}"/>
      <path d="{line(bottom)}"/>
    </g>
  </g>
</svg>
"""
pathlib.Path(__file__).with_name("AppIcon.svg").write_text(svg)
